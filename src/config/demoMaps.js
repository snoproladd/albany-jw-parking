/**
 * @file src/config/demoMaps.js
 * @description Sample Maps-page content shown on the demo site only.
 *
 * The real Maps page lists files synced from SharePoint into Blob Storage,
 * which demo and production share. The demo never links to those files;
 * instead it shows these descriptive sample tiles so reviewers can see what
 * the feature does without exposing real documents.
 *
 * Shape matches groupMapFilesIntoSections() in routes/mapsRoutes.js, plus
 * `isSample: true`, which views/maps.ejs renders as a non-clickable badge.
 */

/**
 * @typedef {Object} DemoMapFile
 * @property {string}      name
 * @property {string}      description
 * @property {null}        webUrl       - Always null: samples have no file.
 * @property {string}      mimeType
 * @property {null}        lastModified
 * @property {null}        size
 * @property {null}        scribbleUrl
 * @property {null}        embedUrl
 * @property {true}        isSample
 */

/**
 * Build one sample tile.
 * @param {string} name
 * @param {string} description
 * @returns {DemoMapFile}
 */
function sample(name, description) {
    return {
        name,
        description,
        webUrl: null,
        mimeType: "application/pdf",
        lastModified: null,
        size: null,
        scribbleUrl: null,
        embedUrl: null,
        isSample: true,
    };
}

